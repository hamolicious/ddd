#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { rollup } from "rollup";
import { dts } from "rollup-plugin-dts";

const web = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export async function buildPluginDts({ root, outDir, entry }) {
  const manifest = JSON.parse(readFileSync(join(root, "manifest.json"), "utf8"));
  const input = entry ?? join(root, "src", "index.tsx");
  const warnings = [];
  const bundle = await rollup({
    input,
    external: (id) => !id.startsWith(".") && !isAbsolute(id),
    onwarn: (warning) => warnings.push(warning),
    plugins: [
      dts({
        tsconfig: join(web, "tsconfig.json"),
        compilerOptions: { noEmit: false, declaration: true, emitDeclarationOnly: true, noUnusedLocals: false },
      }),
    ],
  });
  const { output } = await bundle.generate({ format: "es" });
  await bundle.close();
  for (const warning of warnings) {
    if (warning.code !== "CIRCULAR_DEPENDENCY") console.warn(`  ${manifest.id} d.ts: ${warning.message}`);
  }
  const code = output.find((chunk) => chunk.type === "chunk")?.code ?? "export {};\n";
  const file = join(outDir, "frontend", "index.d.ts");
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, wrap(manifest, code));
  return file;
}

export function wrap(manifest, code) {
  const body = code
    .split("\n")
    .filter((line) => !line.startsWith("//# sourceMappingURL"))
    .map((line) => line.replace(/^(export\s+)?declare\s+/, "$1"))
    .map((line) => (line.length > 0 ? `  ${line}` : line))
    .join("\n")
    .trimEnd();
  return [
    "/**",
    ` * \`plugin:${manifest.id}\` — the exports of ${manifest.id} ${manifest.version}.`,
    " *",
    " * Generated by web/scripts/build-plugin-dts.mjs from the plugin's src/index.tsx. Do not edit.",
    ` * Import it with \`import { … } from "plugin:${manifest.id}"\` and list "${manifest.id}" under`,
    " * the manifest's `dependencies`.",
    " */",
    `declare module "plugin:${manifest.id}" {`,
    body,
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [root, outDir] = process.argv.slice(2);
  if (!root || !outDir) {
    console.error("usage: build-plugin-dts.mjs <plugin-dir> <out-dir>");
    process.exit(2);
  }
  const file = await buildPluginDts({ root: resolve(root), outDir: resolve(outDir) });
  console.log(`wrote ${file}`);
}
