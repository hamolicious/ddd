#!/usr/bin/env node
/**
 * Generate the manifest types for both halves from `schema/manifest.schema.json`
 * (PLUGIN-PROTOCOLS §9 step 1, the review's P0).
 *
 * ```
 * schema/manifest.schema.json
 *   ├─> web/kernel-api/src/manifest.generated.ts        interfaces + the schema as a const
 *   └─> backend/crates/server/src/manifest_types.rs     serde structs + KERNEL_VERSION
 * ```
 *
 * The validators are not generated line by line: each language has one small interpreter
 * over the same schema (`manifest.ts`, `manifest_schema.rs`), and the fixture corpus in
 * `schema/fixtures/manifests.json` pins that both give the same answer. The `@kernel`
 * version is in the schema too (`x-kernel-version`), so the server's install check and the
 * client's boot check can no longer drift apart.
 *
 * `node web/scripts/gen-manifest.mjs` writes both files; `--check` writes nothing and exits
 * non-zero when either is stale (the web check runs it).
 */

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const schemaPath = resolve(repo, "schema/manifest.schema.json");
const tsOut = resolve(repo, "web/kernel-api/src/manifest.generated.ts");
const rsOut = resolve(repo, "backend/crates/server/src/manifest_types.rs");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const defs = schema.$defs ?? {};
const refName = (ref) => ref.replace("#/$defs/", "");

const HEADER = "GENERATED by web/scripts/gen-manifest.mjs from schema/manifest.schema.json. Do not edit.";

// ---------------------------------------------------------------------------
// TypeScript
// ---------------------------------------------------------------------------

function tsType(node) {
  if (node.$ref) return refName(node.$ref);
  if (node.enum) return node.enum.map((v) => JSON.stringify(v)).join(" | ");
  switch (node.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `readonly (${tsType(node.items)})[]`;
    case "object":
      if (node.additionalProperties && typeof node.additionalProperties === "object") {
        return `Readonly<Record<string, ${tsType(node.additionalProperties)}>>`;
      }
      return "Readonly<Record<string, unknown>>";
    default:
      return "unknown";
  }
}

function tsDoc(text, indent = "") {
  if (!text) return "";
  return `${indent}/** ${text} */\n`;
}

function tsInterface(name, node, root = false) {
  const required = new Set(node.required ?? []);
  let out = tsDoc(node.description);
  out += `export interface ${name} {\n`;
  for (const [key, prop] of Object.entries(node.properties ?? {})) {
    out += tsDoc(prop.description, "  ");
    const safeKey = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
    // `x-rust-always`: the server always serializes it, so readers may rely on it being there.
    const present = required.has(key) || prop["x-rust-always"];
    out += `  readonly ${safeKey}${present ? "" : "?"}: ${tsType(prop)};\n`;
  }
  if (root) {
    out += "  /** `x-*` keys are the author's own metadata, passed through untouched. */\n";
    out += "  readonly [extension: `x-${string}`]: unknown;\n";
  }
  out += "}\n";
  return out;
}

function renderTs() {
  let out = `/**\n * ${HEADER}\n */\n\n`;
  out += `/** The \`@kernel\` contract version (\`x-kernel-version\`). The server's \`KERNEL_VERSION\` is generated from the same line. */\n`;
  out += `export const MANIFEST_KERNEL_VERSION = ${JSON.stringify(schema["x-kernel-version"])};\n\n`;
  for (const [name, node] of Object.entries(defs)) out += `${tsInterface(name, node)}\n`;
  out += tsInterface("PluginManifest", schema, true);
  out += "\n/** The schema itself, for `validateManifest`. */\n";
  out += `export const MANIFEST_SCHEMA: ManifestSchemaNode = ${JSON.stringify(stripForRuntime(schema), null, 2)};\n\n`;
  out += `/** The subset of JSON Schema the validators interpret. */
export interface ManifestSchemaNode {
  readonly $ref?: string;
  readonly type?: "object" | "array" | "string" | "number" | "integer" | "boolean";
  readonly required?: readonly string[];
  readonly properties?: Readonly<Record<string, ManifestSchemaNode>>;
  readonly additionalProperties?: ManifestSchemaNode | boolean;
  readonly propertyNames?: { readonly format?: string };
  readonly items?: ManifestSchemaNode;
  readonly enum?: readonly unknown[];
  readonly format?: string;
  readonly minimum?: number;
  readonly $defs?: Readonly<Record<string, ManifestSchemaNode>>;
}
`;
  return out;
}

/** Only what the interpreters read: descriptions and `x-*` generator hints stay in the source. */
function stripForRuntime(node) {
  if (Array.isArray(node)) return node.map(stripForRuntime);
  if (typeof node !== "object" || node === null) return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "description" || key === "title" || key.startsWith("x-") || key === "$schema" || key === "$id") continue;
    out[key] = key === "properties" || key === "$defs"
      ? Object.fromEntries(Object.entries(value).map(([k, v]) => [k, stripForRuntime(v)]))
      : stripForRuntime(value);
  }
  return out;
}

// ---------------------------------------------------------------------------
// Rust
// ---------------------------------------------------------------------------

const rustName = (defName) => defs[defName]?.["x-rust-name"] ?? defName;

function snake(key) {
  return key
    .replace(/-/g, "_")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .toLowerCase();
}

function rsDoc(text, indent = "") {
  if (!text) return "";
  return `${indent}/// ${text}\n`;
}

function rsField(key, prop, isRequired) {
  const field = prop["x-rust-field"] ?? snake(key);
  const attrs = [];
  let type;
  if (field !== key) attrs.push(`rename = ${JSON.stringify(key)}`);
  const inner = (node) => {
    if (node.$ref) return rustName(refName(node.$ref));
    if (node["x-rust-type"]) return node["x-rust-type"];
    switch (node.type) {
      case "string":
        return "String";
      case "number":
        return "f64";
      case "integer":
        return "u32";
      case "boolean":
        return "bool";
      case "array":
        return `Vec<${inner(node.items)}>`;
      case "object":
        return `BTreeMap<String, ${node.additionalProperties && typeof node.additionalProperties === "object" ? inner(node.additionalProperties) : "serde_json::Value"}>`;
      default:
        return "serde_json::Value";
    }
  };
  const base = inner(prop);
  if (isRequired) {
    type = base;
  } else if (prop["x-rust-default"]) {
    type = base;
    attrs.unshift("default");
    if (prop["x-rust-skip-if"]) attrs.push(`skip_serializing_if = ${JSON.stringify(prop["x-rust-skip-if"])}`);
  } else if (prop.type === "array" && !prop["x-rust-option"]) {
    type = base;
    attrs.unshift("default");
    if (!prop["x-rust-always"]) attrs.push('skip_serializing_if = "Vec::is_empty"');
  } else if (prop.type === "object" && !prop.$ref) {
    type = base;
    attrs.unshift("default");
    attrs.push('skip_serializing_if = "BTreeMap::is_empty"');
  } else if (prop.type === "boolean") {
    type = base;
    attrs.unshift("default");
    attrs.push('skip_serializing_if = "std::ops::Not::not"');
  } else {
    type = `Option<${base}>`;
    attrs.unshift("default");
    attrs.push('skip_serializing_if = "Option::is_none"');
  }
  let out = rsDoc(prop.description, "    ");
  if (attrs.length) out += `    #[serde(${attrs.join(", ")})]\n`;
  out += `    pub ${field}: ${type},\n`;
  return out;
}

function rsStruct(name, node) {
  const derive = node["x-rust-derive"] ?? ["Debug", "Clone", "Serialize", "Deserialize"];
  const required = new Set(node.required ?? []);
  let out = rsDoc(node.description);
  out += `#[derive(${derive.join(", ")})]\n`;
  out += `pub struct ${name} {\n`;
  for (const [key, prop] of Object.entries(node.properties ?? {})) out += rsField(key, prop, required.has(key));
  if (node["x-rust-extra"]) {
    out += "    /// Everything else in the file, passed through untouched (`x-*` keys, and anything a\n";
    out += "    /// newer server understands that this one does not).\n";
    out += "    #[serde(flatten)]\n";
    out += "    pub extra: BTreeMap<String, serde_json::Value>,\n";
  }
  out += "}\n";
  return out;
}

function renderRs() {
  let out = `//! ${HEADER}\n//!\n//! The manifest's serde types. Methods live in \`plugins.rs\`; validation is\n//! \`manifest_schema.rs\`, an interpreter over the same schema.\n\n`;
  out += "use std::collections::BTreeMap;\n\nuse serde::{Deserialize, Serialize};\n\n";
  out += `/// The \`@kernel\` contract version this server implements (\`x-kernel-version\`). The web\n/// bundle's \`KERNEL_API_VERSION\` is generated from the same line.\n`;
  out += `pub const KERNEL_VERSION: &str = ${JSON.stringify(schema["x-kernel-version"])};\n\n`;
  out += rsStruct(schema["x-rust-name"] ?? "PluginManifest", schema);
  for (const [name, node] of Object.entries(defs)) out += `\n${rsStruct(rustName(name), node)}`;
  return out;
}

// ---------------------------------------------------------------------------

/**
 * rustfmt the Rust output so `cargo fmt --check` and `--check` here agree. The generator's
 * own line breaks are then irrelevant, and the checked-in file is exactly what fmt wants.
 */
function rustfmt(source) {
  const run = spawnSync("rustfmt", ["--edition", "2024", "--emit", "stdout"], { input: source, encoding: "utf8" });
  if (run.status !== 0) {
    console.error(run.stderr || "rustfmt failed");
    process.exit(1);
  }
  return run.stdout;
}

const outputs = [
  [tsOut, renderTs()],
  [rsOut, rustfmt(renderRs())],
];

const check = process.argv.includes("--check");
let stale = 0;
for (const [path, content] of outputs) {
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {
    /* missing counts as stale */
  }
  if (current === content) continue;
  if (check) {
    stale += 1;
    console.error(`stale: ${path.slice(repo.length + 1)} (run \`node web/scripts/gen-manifest.mjs\`)`);
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${path.slice(repo.length + 1)}`);
  }
}
if (stale > 0) process.exit(1);
