#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const PROSE = new Set(["Markdown", "Text", "Plain Text"]);

const GENERATED = [
  "graphify-out",
  "app/.metadata",
  "app/linux/flutter",
  "app/windows/flutter",
  "app/macos/Flutter/GeneratedPluginRegistrant.swift",
  "desktop/permissions/autogenerated",
  "*.lock",
  "*.pbxproj",
  "*.storyboard",
  "*.xib",
];

const SELF_HOSTER_TEMPLATES = [".env.example"];

const COMMENTLESS_FORMATS = new Set([".json"]);

const TOKEI_STAND_INS = new Map([
  [".rc", ".c"],
  [".plist", ".xml"],
  [".entitlements", ".xml"],
  [".manifest", ".xml"],
  [".xcscheme", ".xml"],
  [".xcworkspacedata", ".xml"],
  [".xcsettings", ".xml"],
  [".properties", ".sh"],
  [".webmanifest", ".json"],
]);

const SHEBANG_STAND_INS = new Map([
  ["bash", ".sh"],
  ["sh", ".sh"],
  ["node", ".mjs"],
]);

const HASH_COMMENTED_NAMES = new Set([".gitignore", ".dockerignore", "gitignore"]);

const FUNCTIONAL = [
  /^#!/,
  /^# syntax=/,
  /^<!--DDD_[A-Z_]+-->$/,
  /^\/\/\/ <reference /,
  /^\/\/ @ts-expect-error\b/,
  /^\/\/ eslint-disable/,
  /^\/\* eslint-disable[^*]*\*\/$/,
  /^\/\/ prettier-ignore$/,
  /^\/\* @vite-ignore \*\/$/,
  /^\/\/ ignore(_for_file)?: /,
];

function isGenerated(path) {
  return GENERATED.some((entry) =>
    entry.startsWith("*.") ? path.endsWith(entry.slice(1)) : path === entry || path.startsWith(`${entry}/`),
  );
}

function repositoryFiles() {
  const run = spawnSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (run.status !== 0) {
    console.error(`could not list repository files: ${run.stderr || run.error?.message}`);
    process.exit(2);
  }
  return run.stdout
    .split("\0")
    .filter(Boolean)
    .filter((path) => !isGenerated(path) && !SELF_HOSTER_TEMPLATES.includes(path))
    .filter((path) => existsSync(join(root, path)));
}

function interpreterOf(text) {
  const shebang = /^#!\s*(\S+)(?:\s+(\S+))?/.exec(text);
  if (!shebang) return undefined;
  const program = basename(shebang[1]);
  return program === "env" ? shebang[2] : program;
}

function standInPath(path, text) {
  if (HASH_COMMENTED_NAMES.has(basename(path))) return `${path}.sh`;
  if (extname(path) === "") {
    const standIn = SHEBANG_STAND_INS.get(interpreterOf(text) ?? "");
    if (standIn) return `${path}${standIn}`;
  }
  const standIn = TOKEI_STAND_INS.get(extname(path));
  return standIn ? `${path}${standIn}` : path;
}

function withoutFunctionalLines(text) {
  return text
    .split("\n")
    .map((line) => (FUNCTIONAL.some((pattern) => pattern.test(line.trim())) ? "" : line))
    .join("\n");
}

function stageTextFiles(paths, stage) {
  const staged = new Map();
  for (const path of paths) {
    const bytes = readFileSync(join(root, path));
    if (bytes.includes(0)) continue;
    const text = bytes.toString("utf8");
    const target = standInPath(path, text);
    mkdirSync(dirname(join(stage, target)), { recursive: true });
    writeFileSync(join(stage, target), withoutFunctionalLines(text));
    staged.set(target, path);
  }
  return staged;
}

function tokei(stage) {
  const run = spawnSync("tokei", [".", "--files", "--hidden", "--no-ignore", "--output", "json"], {
    cwd: stage,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });
  if (run.error) {
    console.error(`could not run tokei: ${run.error.message}`);
    process.exit(2);
  }
  if (run.status !== 0) {
    console.error(run.stderr);
    process.exit(2);
  }
  return JSON.parse(run.stdout);
}

function commentLines(stats) {
  let total = stats.comments;
  for (const blob of Object.values(stats.blobs ?? {})) total += commentLines(blob);
  return total;
}

const stage = mkdtempSync(join(tmpdir(), "ddd-comments-"));
const offenders = [];
const unrecognised = [];
try {
  const staged = stageTextFiles(repositoryFiles(), stage);
  const recognised = new Set();
  for (const [language, summary] of Object.entries(tokei(stage))) {
    if (language === "Total") continue;
    for (const report of summary.reports ?? []) {
      const path = staged.get(relative(stage, resolve(stage, report.name)));
      if (path === undefined) continue;
      recognised.add(path);
      if (PROSE.has(language)) continue;
      const comments = commentLines(report.stats);
      if (comments > 0) offenders.push({ path, language, comments });
    }
  }
  for (const path of staged.values()) {
    if (!recognised.has(path) && !COMMENTLESS_FORMATS.has(extname(path))) unrecognised.push(path);
  }
} finally {
  rmSync(stage, { recursive: true, force: true });
}

if (offenders.length > 0) {
  offenders.sort((a, b) => a.path.localeCompare(b.path));
  console.error("Comments or docstrings found. Explain through naming, or in the directory's README:");
  for (const { path, language, comments } of offenders) {
    console.error(`  ${path} (${language}): ${String(comments)} comment line${comments === 1 ? "" : "s"}`);
  }
}
if (unrecognised.length > 0) {
  unrecognised.sort();
  console.error("tokei does not recognise these files, so their comments cannot be checked. Map them in scripts/check-comments.mjs:");
  for (const path of unrecognised) console.error(`  ${path}`);
}
if (offenders.length > 0 || unrecognised.length > 0) process.exit(1);
console.log("no comments or docstrings");
